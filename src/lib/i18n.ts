const dict = { en, hi };

export function useT() {
  const { lang } = useApp();
  return (key: Key, vars?: Record<string, string | number>) => {
    let s = dict[lang][key];
    if (vars) for (const k in vars) s = s.replace(`{${k}}`, String(vars[k]));
    return s;
  };
}

export function useUnit() {
  const t = useT();
  return (u: Unit) => t(`unit_${u}`);
}

